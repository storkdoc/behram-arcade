# convert every raw/*.mp4 into the game's clips/ folder + clips/manifest.js
import os, sys, json, subprocess, glob
OUT = '/workspace/chess-clips-wt/games/living-chess/clips'
os.makedirs(OUT, exist_ok=True)
skip = set(open('skip.txt').read().split()) if os.path.exists('skip.txt') else set()
man = []
for f in sorted(glob.glob('raw/*.mp4')):
    id = os.path.basename(f)[:-4]
    if id in skip: continue
    parts = id.split('-')  # Bw-dark-demise-melt
    t, side, sq, e = parts[0][0], 0 if parts[0][1] == 'w' else 1, parts[1], parts[2]
    style = parts[3] if len(parts) > 3 else ''
    o = f'{OUT}/{id}.webp'
    if not os.path.exists(o) or os.path.getmtime(o) < os.path.getmtime(f):
        r = json.loads(subprocess.check_output(['python3', 'convert.py', f, o, '15', '224']).decode().strip().split('\n')[-1])
        json.dump(r, open(f'meta/{id}.json', 'w'))
    r = json.load(open(f'meta/{id}.json'))
    man.append(dict(f=id + '.webp', t=t, side=side, light=sq == 'light', e=e, s=style, n=r['n'], cols=r['cols'], rows=r['rows'], fps=r['fps'], kb=round(os.path.getsize(o) / 1024)))
js = ('/* LIVING CHESS — on-board emotion clips (generated by tools/clips/build.py; do not edit by hand).\n'
      '   f atlas file · t piece · side 0 white / 1 black · light square? · e emotion · s style · n frames · cols x rows grid · fps */\n'
      'export const CLIPS = [\n' + ',\n'.join('  ' + json.dumps({k: v for k, v in m.items() if k != 'kb'}, separators=(',', ':')) for m in man) + '\n];\n')
open(f'{OUT}/manifest.js', 'w').write(js)
print(len(man), 'clips', sum(m['kb'] for m in man), 'KB total, max', max(m['kb'] for m in man), 'KB')
