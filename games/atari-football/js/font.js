  const ADV = 6, LINE = 9;

  /** width in pixels of a string at the given scale */
  function width(s, sc = 1) { return s.length ? (s.length * ADV - 1) * sc : 0; }

  /** draw text; align: 'l' | 'c' | 'r' */
  function draw(ctx, s, x, y, color, sc = 1, align = 'l') {
    s = String(s).toUpperCase();
    if (align === 'c') x -= Math.floor(width(s, sc) / 2); else if (align === 'r') x -= width(s, sc);
    ctx.fillStyle = color;
    for (let i = 0; i < s.length; i++) {
      const px = P[s[i]];
      if (px) for (let j = 0; j < px.length; j += 2) ctx.fillRect(x + px[j] * sc, y + px[j + 1] * sc, sc, sc);
      x += ADV * sc;
    }
  }
  /** text with a 1-pixel drop shadow (keeps it readable over the field) */
  function shadow(ctx, s, x, y, color, sc = 1, align = 'l', sh = '#000') {
    draw(ctx, s, x + sc, y + sc, sh, sc, align); draw(ctx, s, x, y, color, sc, align);
  }
  /** wrap text into lines that fit maxW pixels */
  function wrap(s, maxW, sc = 1) {
    const out = []; let line = '';
    for (const w of String(s).split(' ')) {
      const t = line ? line + ' ' + w : w;
      if (width(t, sc) > maxW && line) { out.push(line); line = w; } else line = t;
    }
    if (line) out.push(line);
    return out;
  }
  return { draw, shadow, width, wrap, ADV, LINE };
